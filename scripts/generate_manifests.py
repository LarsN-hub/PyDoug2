"""
Discover all required dependencies for pyinstaller build.
"""

import importlib
import pkgutil
from pathlib import Path


def build_manifest(package_name: str, output_path: Path) -> None:
    """
    Builds a manifest for PyDoug's core and napari packages to find all dependencies.

    Parameters
    ----------
    package_name: str
        The name of the package.
    output_path: Path
        The output path for the manifest file.
    """

    package = importlib.import_module(package_name)
    names = [
        m.name
        for m in pkgutil.walk_packages(package.__path__, prefix=f"{package_name}.")
        if not m.name.rsplit(".", 1)[-1].startswith("_")
    ]
    if "pydoug_core.testing" in names:
        names.remove("pydoug_core.testing")
    output_path.write_text(
        "# Auto-generated by scripts/generate_manifests.py - DO NOT EDIT!\n"
        f"OPERATION_MODULES = {names!r}\n"
    )


if __name__ == "__main__":
    build_manifest(
        "pydoug_core", Path("packages/pydoug-core/src/pydoug_core/_manifest.py")
    )
    build_manifest(
        "pydoug_napari._operations",
        Path("packages/pydoug-napari/src/pydoug_napari/_operations/_manifest.py"),
    )
